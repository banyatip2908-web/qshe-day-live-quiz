export function validateQuestions(input) {
  if (!Array.isArray(input) || input.length < 10 || input.length > 30) throw new Error('คลังคำถามต้องมี 10–30 ข้อ');
  return input.map((q,i) => {
    const text=String(q.text||'').trim();
    const choices=Array.isArray(q.choices)?q.choices.map(x=>String(x||'').trim()):[];
    const correct=Number(q.correct),seconds=Number(q.seconds);
    if(!text || text.length>240)throw new Error(`ข้อ ${i+1}: คำถามต้องมีความยาว 1–240 ตัวอักษร`);
    if(choices.length!==4||choices.some(x=>!x||x.length>125))throw new Error(`ข้อ ${i+1}: ต้องมีตัวเลือกครบ 4 ข้อ`);
    if(!Number.isInteger(correct)||correct<0||correct>3)throw new Error(`ข้อ ${i+1}: เลือกเฉลยที่ถูกต้อง`);
    if(!Number.isInteger(seconds)||seconds<10||seconds>60)throw new Error(`ข้อ ${i+1}: เวลาต้องอยู่ระหว่าง 10–60 วินาที`);
    return {text,choices,correct,seconds,topic:String(q.topic||'Climate Change').slice(0,40),source:String(q.source||'').slice(0,60),explanation:String(q.explanation||'').slice(0,350)};
  });
}

export function shuffledOrder(count, rng=Math.random) {
  const order=Array.from({length:count},(_,i)=>i);
  for(let i=count-1;i>0;i--){const j=Math.floor(rng()*(i+1));[order[i],order[j]]=[order[j],order[i]];}
  if(count>1&&order.every((v,i)=>v===i)) [order[0],order[1]]=[order[1],order[0]];
  return order;
}

// Picks exactly 10 unique questions; when the bank has all 3 vinyls, use 3+3+4 for balanced learning.
export function selectRoundQuestions(bank, rng=Math.random) {
  const all=shuffledOrder(bank.length,rng), groups=[[],[],[]],other=[];
  for(const i of all){
    const category=(bank[i].source||'')+' '+(bank[i].topic||'');
    const m=category.match(/(?:แผ่นที่|ป้าย)\s*([123])/);
    if(m)groups[Number(m[1])-1].push(i); else other.push(i);
  }
  let selected=[];
  if(groups.every(g=>g.length>=3)) {
    selected=groups.flatMap(g=>g.slice(0,3));
    const remains=all.filter(i=>!selected.includes(i));
    selected.push(remains[0]);
  } else selected=all.slice(0,10);
  return shuffledOrder(selected.length,rng).map(j=>selected[j]);
}

export function calculatePoints(correct,selected,seconds,remainingMs,multiplier=1){
  if(selected!==correct||remainingMs<=0)return 0;
  const fraction=Math.min(1,Math.max(0,remainingMs/(seconds*1000)));
  return Math.round((500+500*fraction)*multiplier);
}

export function getRanking(players,roundId){
  const result=[...players.values()].map(p=>({id:p.id,name:p.name,score:p.roundId===roundId?p.score:0}));
  result.sort((a,b)=>b.score-a.score||a.name.localeCompare(b.name,'th'));
  return result.map((p,i)=>({...p,rank:i+1}));
}
// Count only members of the roster frozen when the host started this round.
// Each player is counted at most once, including after reconnects or repeat messages.
export function countAnsweredPlayers(players, participantIds, roundId, questionIndex) {
  if (!Array.isArray(participantIds)) return 0;
  let count=0;
  for(const id of new Set(participantIds)){
    const p=players.get(id);
    if(p && p.roundId===roundId && p.answers &&
       Object.prototype.hasOwnProperty.call(p.answers, questionIndex)) count++;
  }
  return count;
}
